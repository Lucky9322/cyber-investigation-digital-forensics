/**
 * Service to load entity graphs for cases.
 * Connects to live FastAPI backend when available, or gracefully falls back to rich forensic mock dataset.
 */
export async function getCaseEntityGraph(caseId: string, token?: string | null): Promise<EntityGraphData> {
  // If the backend has a live /api/cases/{caseId}/entities endpoint in the future, we attempt fetch:
  const backendUrl = process.env.NEXT_PUBLIC_BACKEND_URL || "http://127.0.0.1:8000";

  if (token) {
    try {
      const res = await fetch(`${backendUrl}/api/cases/${caseId}/entities`, {
        method: "GET",
        headers: {
          Authorization: `Bearer ${token}`,
          "Content-Type": "application/json",
        },
      });
      if (res.ok) {
        const liveData = await res.json();
        if (liveData && liveData.nodes && liveData.nodes.length > 0) {
          return liveData;
        }
      }
    } catch {
      // Backend endpoint not active yet for module 7; seamlessly fall back to mock dataset
    }
  }

  // Graceful simulation latency
  await new Promise((resolve) => setTimeout(resolve, 300));

  // If caseId matches one of mock keys, return it:
  if (MOCK_CASE_GRAPHS[caseId]) {
    return JSON.parse(JSON.stringify(MOCK_CASE_GRAPHS[caseId]));
  }

  // If a generic caseId was requested, adapt the primary mock data with the requested case ID
  const defaultGraph = JSON.parse(JSON.stringify(MOCK_CASE_GRAPHS["case-dark-nexus"])) as EntityGraphData;
  defaultGraph.case_info.case_id = caseId;
  defaultGraph.case_info.case_title = `Forensic Case: ${caseId.slice(0, 16)}`;
  return defaultGraph;
}
